// 读取后台图标配置对应的品牌图形
function resolveBrand(icon: string, title: string) {
  const normalized = icon.trim().toLowerCase();
  if (normalized.includes("alipay")) return brandIcons.alipay;
  if (normalized.includes("weixin") || normalized.includes("wechat")) return brandIcons.wechat;
  if (normalized.includes("kofi") || normalized.includes("ko-fi")) return brandIcons.kofi;
  if (normalized.includes("afdian")) return brandIcons.afdian;
  if (!normalized) {
    if (title.includes("支付宝")) return brandIcons.alipay;
    if (title.includes("微信")) return brandIcons.wechat;
    if (/ko-?fi/i.test(title)) return brandIcons.kofi;
    if (title.includes("爱发电")) return brandIcons.afdian;
  }
  return null;
}

// 打赏方式图标：支持官方品牌别名、emoji、图片地址与首字兜底
export default function SponsorMethodIcon({
  icon,
  title,
  className = "",
}: {
  icon: string;
  title: string;
  className?: string;
}) {
  const [failed, setFailed] = useState(false);
  const trimmed = icon.trim();
  const brand = resolveBrand(trimmed, title);
  const isImage = /^https?:\/\//i.test(trimmed) || trimmed.startsWith("/");

  return (
    <span className={`flex shrink-0 items-center justify-center ${className}`}>
      {brand ? (
        <svg aria-hidden viewBox={brand.viewBox} className="size-[1em] fill-current">
          <path d={brand.path} />
        </svg>
      ) : isImage && !failed ? (
        // eslint-disable-next-line @next/next/no-img-element -- 图标来自后台上传或外部地址
        <img
          src={trimmed}
          alt=""
          className="size-full object-contain"
          loading="lazy"
          decoding="async"
          onError={() => setFailed(true)}
        />
      ) : (
        <span aria-hidden>{trimmed || title.trim().charAt(0) || "赏"}</span>
      )}
    </span>
  );
}
